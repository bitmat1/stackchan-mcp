#!/bin/zsh
# Builds Stack-chan.app: one double-click starts the gateway, opens the
# control panel and (with the Claude brain) the Claude voice session.
# Quitting the app stops the gateway it started.
#
#   scripts/make-app.sh [destination folder]    (default: ~/Applications)
#
# Re-run after moving the repository, since the app stores its path.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-$HOME/Applications}"
UV="$(command -v uv || echo /opt/homebrew/bin/uv)"
LOG="$HOME/Library/Logs/stackchan-app.log"
APP="$DEST/Stack-chan.app"

if [[ ! -x "$UV" ]]; then
  echo "uv not found; install it first (brew install uv)." >&2
  exit 1
fi
mkdir -p "$DEST"

SCRIPT="$(mktemp -t stackchan-app).applescript"
cat >"$SCRIPT" <<EOF
-- Generated by scripts/make-app.sh; edit that script instead.
property launcherPid : ""

on run
	-- exec, so the recorded PID is uv itself (uv passes SIGTERM on to the app)
	set launcherPid to do shell script "export PATH=/opt/homebrew/bin:\$HOME/.local/bin:\$PATH; (cd " & quoted form of "$ROOT/gateway" & " && exec " & quoted form of "$UV" & " run stackchan-mcp app >> " & quoted form of "$LOG" & " 2>&1) & echo \$!"
end run

on quit
	if launcherPid is not "" then
		do shell script "kill -TERM " & launcherPid & " 2>/dev/null || true"
	end if
	-- Belt and braces: any other launcher instance (it stops its own gateway).
	do shell script "pkill -TERM -f 'stackchan-mcp app' 2>/dev/null || true"
	continue quit
end quit
EOF

rm -rf "$APP"
osacompile -s -o "$APP" "$SCRIPT"
rm -f "$SCRIPT"
echo "Built $APP"
echo "Log: $LOG (gateway log: ~/Library/Logs/stackchan-gateway.log)"
